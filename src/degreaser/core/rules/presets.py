PRESETS_BY_ID = {p.id: p for p in PRESETS}


def presets_for(kind: RuleKind) -> list[Preset]:
    return [p for p in PRESETS if p.kind == kind]


def _dedupe(patterns: Iterable[str]) -> list[str]:
    seen: set[str] = set()
    out = []
    for p in patterns:
        if p not in seen:
            seen.add(p)
            out.append(p)
    return out


@dataclass
class RuleConfig:
    """Which presets are on, plus the project's own patterns, for each list."""

    presets: set[str] = field(default_factory=lambda: {p.id for p in PRESETS if p.default})
    custom_delete: list[str] = field(default_factory=list)
    custom_keep: list[str] = field(default_factory=list)

    def patterns(self, kind: RuleKind) -> list[str]:
        """The flattened list for the rules table: presets in display order, then custom."""
        from_presets = [
            pat for p in presets_for(kind) if p.id in self.presets for pat in p.patterns
        ]
        custom = self.custom_delete if kind == "always_delete" else self.custom_keep
        return _dedupe([*from_presets, *custom])

    def to_dict(self) -> dict[str, Any]:
        return {
            "presets": sorted(self.presets),
            "custom_delete": self.custom_delete,
            "custom_keep": self.custom_keep,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> RuleConfig:
        return cls(
            presets={p for p in data.get("presets", []) if p in PRESETS_BY_ID},
            custom_delete=list(data.get("custom_delete", [])),
            custom_keep=list(data.get("custom_keep", [])),
        )

    @classmethod
    def infer(cls, always_delete: list[str], always_keep: list[str]) -> RuleConfig:
        """Recover presets from flat pattern lists (the text editor, or older projects).

        A preset counts as on when every one of its patterns is present; whatever no
        selected preset accounts for becomes a custom pattern, in its original order.
        """
        selected: set[str] = set()
        custom: dict[RuleKind, list[str]] = {}
        lists: tuple[tuple[RuleKind, list[str]], ...] = (
            ("always_delete", always_delete),
            ("always_keep", always_keep),
        )
        for kind, flat in lists:
            present = set(flat)
            on = [p for p in presets_for(kind) if p.patterns and set(p.patterns) <= present]
            selected |= {p.id for p in on}
            covered = {pat for p in on for pat in p.patterns}
            custom[kind] = _dedupe(pat for pat in flat if pat not in covered)
        return cls(selected, custom["always_delete"], custom["always_keep"])
